#!/usr/bin/env bash
# Read-only host probe. Prints one servers/<id>.toml snippet on stdout.
# Run: ssh HOST 'hostname && bash -s' < tools/remote-script-ip.sh
main() {
  have() { command -v "$1" >/dev/null 2>&1; }
  to() { if have timeout; then timeout 5 "$@" </dev/null 2>/dev/null; else "$@" </dev/null 2>/dev/null; fi; }
  esc() { tr -d '\r' | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g'; }
  arr() {
    local first=1 x
    printf '['
    while IFS= read -r x; do
      [ -n "$x" ] || continue
      [ $first = 1 ] || printf ', '
      first=0
      printf '"%s"' "$(printf '%s' "$x" | esc)"
    done
    printf ']'
  }

  SUDO=""
  if [ "$(id -u 2>/dev/null)" = 0 ]; then SUDOMSG="root"
  elif have sudo && sudo -n true </dev/null >/dev/null 2>&1; then SUDO="sudo -n"; SUDOMSG="sudo -n"
  else SUDOMSG="none (non-root, no passwordless sudo): process names may show as ?"; fi

  host=$(hostname -s 2>/dev/null || hostname 2>/dev/null)
  id_=$(printf '%s' "$host" | tr 'A-Z' 'a-z' | tr -c 'a-z0-9\n' '-' | sed 's/^-*//; s/-*$//')
  fqdn=$(hostname -f 2>/dev/null || echo "$host")

  ips=""
  if have ip; then
    ips=$(to ip -o -4 addr show scope global | awk '{print $2, $4}' \
      | grep -Ev '^(lo|docker|veth|br-|virbr|cni|flannel|cali|tun|podman)' | awk '{print $2}')
  fi

  os=""
  [ -r /etc/os-release ] && os=$(. /etc/os-release 2>/dev/null; printf '%s' "$PRETTY_NAME")

  kern=$(uname -sr 2>/dev/null)
  arch=$(uname -m 2>/dev/null)
  cpu=$(grep -m1 'model name' /proc/cpuinfo 2>/dev/null | cut -d: -f2- | sed 's/^ *//; s/ *$//')
  ncpu=$(nproc 2>/dev/null)
  memkb=$(awk '/^MemTotal/{print $2}' /proc/meminfo 2>/dev/null)
  mem=""; [ -n "$memkb" ] && mem="$(( (memkb + 524288) / 1048576 )) GiB"
  up=$(uptime -p 2>/dev/null)

  jobs_=$(
    {
      to crontab -l | awk '!/^[ \t]*(#|$)/ && !/^[A-Za-z_][A-Za-z0-9_]*=/ {
        if ($1 ~ /^@/) { k=2; s=$1 } else { k=6; s=$1" "$2" "$3" "$4" "$5 }
        c=$k; for (i=k; i<=NF; i++) if (index($i,"/")) { c=$i; break }
        n=split(c,p,"/"); if (p[n]=="") p[n]="cmd"; print "cron: " s " " p[n] }'
      for f in /etc/crontab /etc/cron.d/*; do
        [ -r "$f" ] || continue
        case "$f" in *.placeholder|*~|*.dpkg-*) continue;; esac
        awk '!/^[ \t]*(#|$)/ && !/^[A-Za-z_][A-Za-z0-9_]*=/ {
          if ($1 ~ /^@/) { s=$1; k=3 } else { s=$1" "$2" "$3" "$4" "$5; k=7 }
          c=$k; for (i=k; i<=NF; i++) if (index($i,"/")) { c=$i; break }
          n=split(c,p,"/"); if (p[n]=="") p[n]="cmd"; print "cron: " s " " p[n] }' "$f" 2>/dev/null
      done
      if have systemctl; then
        to systemctl list-timers --all --no-legend --plain | grep -o '[^ ]*\.timer' | sort -u \
          | grep -Ev '^(apt-daily|apt-daily-upgrade|dpkg-db-backup|e2scrub_all|fstrim|fwupd-refresh|logrotate|man-db|motd-news|systemd-tmpfiles-clean|update-notifier-download|update-notifier-motd|ua-timer|sysstat-.*|mdcheck.*|mdmonitor-oneshot|snapd.snap-repair|lvm2-.*|raid-check|dnf-makecache|shadow|plocate-updatedb|anacron|phpsessionclean|cron-.*)\.timer$' \
          | sed 's/^/timer: /'
      fi
    } | awk '!s[$0]++' | head -50
  )

  svcs=""
  if have systemctl; then
    svcs=$(to systemctl list-units --type=service --state=running --no-legend --plain | awk '{print $1}' \
      | sed 's/\.service$//' \
      | grep -Ev '^(systemd-.*|dbus(-broker)?|cron|crond|atd|rsyslog|syslog-ng|ssh|sshd|openssh-server|getty@.*|serial-getty@.*|console-getty|user@.*|user-runtime-dir@.*|polkit|polkitd|networkd-dispatcher|NetworkManager|wpa_supplicant|irqbalance|multipathd|udisks2|accounts-daemon|avahi-daemon|chrony|chronyd|ntp|ntpd|unattended-upgrades|ModemManager|snapd|lvm2-.*|auditd|gssproxy|rpcbind|tuned|rngd|qemu-guest-agent|vmtoolsd|open-vm-tools|cloud-.*|amazon-ssm-agent|packagekit|fwupd|thermald|upower|rtkit-daemon|apport|ufw|firewalld|sysstat|lxd-.*|plymouth.*|dm-event|mdmonitor|nscd|sssd|postfix|exim4|containerd|docker|podman|libvirtd|wsl-.*)$' \
      | sort -u | head -60)
  fi

  listen=""
  if have ss; then
    listen=$(to $SUDO ss -H -ltnup | awk '{
      split($5,a,":"); port=a[length(a)]; proto=$1
      name="?"; if (match($0,/users:\(\("[^"]+"/)) name=substr($0,RSTART+9,RLENGTH-10)
      printf "%s/%s %s\n", proto, port, name }' | sort -t/ -k2,2n -u | head -60)
  elif have netstat; then
    listen=$(to $SUDO netstat -ltnup | awk 'NR>2 {split($4,a,":"); n=$NF; sub(/^[0-9]*\//,"",n)
      printf "%s/%s %s\n",$1,a[length(a)],(n=="-"?"?":n)}' | sort -u | head -60)
  fi

  containers=""
  for rt in docker podman; do
    have $rt || continue
    c=$(to $SUDO $rt ps --format '{{.Names}}' | head -30 | tr '\n' ',' | sed 's/,$//; s/,/, /g')
    [ -n "$c" ] && containers="$containers$rt: $c"$'\n'
  done

  echo "# Generated by tools/remote-script-ip.sh (read-only). Privilege: $SUDOMSG."
  echo "# Review, add region/role/server_type, then save as servers/<id>.toml."
  echo "id = \"$id_\""
  echo "name = \"$(printf '%s' "$fqdn" | esc)\""
  echo "ips = $(printf '%s\n' "$ips" | arr)"
  [ -n "$os" ] && echo "os = \"$(printf '%s' "$os" | esc)\""
  echo "jobs = $(printf '%s\n' "$jobs_" | arr)"
  echo "systemd_services = $(printf '%s\n' "$svcs" | arr)"
  det=$(
    printf 'Kernel: %s %s\n' "$kern" "$arch"
    printf 'CPU: %s x %s\n' "${ncpu:-?}" "${cpu:-?}"
    printf 'Memory: %s\n' "${mem:-?}"
    printf 'Uptime: %s\n' "${up:-?}"
    [ -n "$containers" ] && printf '%s' "$containers"
    printf 'Listening (proto/port process):\n'
    if [ -n "$listen" ]; then printf '%s\n' "$listen" | sed 's/^/- /'; else printf '(none visible)\n'; fi
  )
  printf 'details = "%s"\n' "$(printf '%s\n' "$det" | esc | awk 'NR>1{printf "\\n"} {printf "%s",$0}')"
}
main </dev/null
